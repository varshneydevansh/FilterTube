#!/usr/bin/env node
// Writes css/paperkit-edges.css: the app's crayon card edge (StudyPaper.crayon: a 1.4 dp line with a
// tiny wobble and soft joins) as nine-slice border images, one per colour and theme. The middle of
// each side wobbles with whole sine cycles, so `border-image-repeat: round` tiles it without a seam
// however long the card is. Colours are BrandPalette's (css/paperkit.css): the hairline, the ink
// and each area's ink at its tile-edge strength, light and night.
// Usage: node scripts/build-crayon-edges.mjs
import fs from 'node:fs';

const SIZE = 200;         // the source square: a long middle, so a side has few tile seams
const SLICE = 20;         // corner box; also the radius the edge is drawn for (20 dp, PaperKit CARD_RADIUS)
const INSET = 1.2;
const RADIUS = SLICE - INSET;
const STROKE = 1.5;

function wobble(side, t) {
    // t: 0..SIZE along the side. The middle: whole sine cycles (seamless when tiled), a slow sway
    // plus a fine crayon jitter, about the app's 0.55 dp deviation.
    const amp = [0.42, 0.36, 0.46, 0.38][side];
    if (t >= SLICE && t <= SIZE - SLICE) {
        const u = (t - SLICE) / (SIZE - 2 * SLICE);
        return amp * (Math.sin(2 * Math.PI * u * (2 + side % 2)) * 0.8 + Math.sin(2 * Math.PI * u * (17 + side)) * 0.35);
    }
    // Ends: a soft bump that is 0 where the middle starts.
    const u = t < SLICE ? t / SLICE : (SIZE - t) / SLICE;
    return amp * 0.55 * Math.sin(Math.PI * u) * (side % 2 ? -1 : 1);
}

function path() {
    const points = [];
    const lo = INSET;
    const hi = SIZE - INSET;
    const push = (x, y) => points.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
    const step = 2.5;
    // Top edge, left to right (normal: up = -y).
    for (let x = lo + RADIUS; x <= hi - RADIUS + 0.01; x += step) push(x, lo - wobble(0, x));
    arc(hi - RADIUS, lo + RADIUS, -90, 0, 0.35);
    for (let y = lo + RADIUS; y <= hi - RADIUS + 0.01; y += step) push(hi + wobble(1, y), y);
    arc(hi - RADIUS, hi - RADIUS, 0, 90, -0.3);
    for (let x = hi - RADIUS; x >= lo + RADIUS - 0.01; x -= step) push(x, hi + wobble(2, x));
    arc(lo + RADIUS, hi - RADIUS, 90, 180, 0.4);
    for (let y = hi - RADIUS; y >= lo + RADIUS - 0.01; y -= step) push(lo - wobble(3, y), y);
    arc(lo + RADIUS, lo + RADIUS, 180, 270, -0.25);
    function arc(cx, cy, from, to, bend) {
        for (let a = from; a <= to; a += 10) {
            const u = (a - from) / (to - from);
            const r = RADIUS + bend * Math.sin(Math.PI * u);
            push(cx + r * Math.cos(a * Math.PI / 180), cy + r * Math.sin(a * Math.PI / 180));
        }
    }
    // Relative moves keep the data URIs small.
    const n = v => (Math.round(v * 10) / 10).toString().replace(/^0\./, '.').replace(/^-0\./, '-.');
    let out = `M${points[0][0]},${points[0][1]}`;
    for (let i = 1; i < points.length; i++) {
        const dx = n(points[i][0] - points[i - 1][0]);
        const dy = n(points[i][1] - points[i - 1][1]);
        out += `l${dx}${dy.startsWith('-') ? '' : ','}${dy}`;
    }
    return `${out}z`;
}

const d = path();
const svg = color => {
    const raw = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${SIZE} ${SIZE}' width='${SIZE}' height='${SIZE}'><path d='${d}' fill='none' stroke='${color}' stroke-width='${STROKE}' stroke-linejoin='round' stroke-linecap='round'/></svg>`;
    return `url("data:image/svg+xml,${encodeURIComponent(raw).replace(/%20/g, ' ').replace(/%2C/g, ',').replace(/%3D/g, '=').replace(/%3A/g, ':').replace(/%2F/g, '/')}")`;
};
const hex = (color, alpha) => {
    const a = Math.round(alpha * 255).toString(16).padStart(2, '0');
    return `${color}${a}`;
};

const light = { line: '#dcd1c2', ink: '#1b1a18', muted: '#625f58', filters: '#a93e31', content: '#1f5f86', kids: '#5a3a07', study: '#28623f', family: '#5b3aa4' };
const night = { line: '#2a3440', ink: '#edf2f7', muted: '#b8c3ce', filters: '#e0796b', content: '#8cc8ea', kids: '#f6d58a', study: '#7fb89a', family: '#b39ae6' };

function block(tones) {
    const lines = [`  --pk-edge-line: ${svg(tones.line)};`, `  --pk-edge-ink: ${svg(hex(tones.ink, 0.55))};`];
    for (const area of ['filters', 'content', 'kids', 'study', 'family']) {
        lines.push(`  --pk-edge-${area}: ${svg(hex(tones[area], 0.22 + 0.06))};`);
    }
    return lines.join('\n');
}

const css = `/* Generated by scripts/build-crayon-edges.mjs; edit the script, not this file.
 * The app's crayon card edge as nine-slice border images (${SLICE}px corners, round-tiled sides). */
:root {
${block(light)}
  --pk-edge-slice: ${SLICE};
}
:root[data-theme="dark"] {
${block(night)}
}
`;
fs.writeFileSync('css/paperkit-edges.css', css);
console.log(`css/paperkit-edges.css: ${css.length} bytes`);
